%% Download datasets required by the tests

mrstRoot = fullfile(orig, "..", "..");

mrstDataDirectory = fullfile( ...
    mrstRoot, "core", "examples", "data");

co2DatasetName = "CO2lab_Sampled_Tables";

co2DatasetDirectory = fullfile( ...
    mrstDataDirectory, co2DatasetName);

co2DatasetUrl = [ ...
    "https://www.sintef.no/contentassets/" ...
    "124f261f170947a6bc51dd76aea66129/" ...
    "co2lab_sampled_tables.zip"];

co2DatasetArchive = fullfile( ...
    mrstDataDirectory, "co2lab_sampled_tables.zip");

datasetAvailable = false;

if isfolder(co2DatasetDirectory)
    datasetContents = dir(co2DatasetDirectory);
    datasetNames = {datasetContents.name};

    datasetContents = datasetContents( ...
        ~ismember(datasetNames, {".", ".."}));

    datasetAvailable = ~isempty(datasetContents);
end

if ~datasetAvailable
    fprintf( ...
        "Downloading required dataset: %s...\n", ...
        co2DatasetName);

    if ~isfolder(mrstDataDirectory)
        mkdir(mrstDataDirectory);
    end

    if isfile(co2DatasetArchive)
        delete(co2DatasetArchive);
    end

    if isfolder(co2DatasetDirectory)
        rmdir(co2DatasetDirectory, "s");
    end

    curlCommand = sprintf( ...
        ['curl --location --fail --silent --show-error ' ...
         '--retry 5 --retry-delay 5 --retry-all-errors ' ...
         '--connect-timeout 30 --max-time 900 ' ...
         '--output "%s" "%s"'], ...
        co2DatasetArchive, co2DatasetUrl);

    [downloadStatus, downloadOutput] = system(curlCommand);

    if downloadStatus ~= 0
        if isfile(co2DatasetArchive)
            delete(co2DatasetArchive);
        end

        error( ...
            "Failed to download %s using curl:\n%s", ...
            co2DatasetName, downloadOutput);
    end

    archiveInformation = dir(co2DatasetArchive);

    if isempty(archiveInformation) || archiveInformation.bytes == 0
        delete(co2DatasetArchive);

        error( ...
            "The downloaded dataset archive is empty: %s", ...
            co2DatasetArchive);
    end

    extractionDirectory = tempname(mrstDataDirectory);
    mkdir(extractionDirectory);

    try
        unzip(co2DatasetArchive, extractionDirectory);
    catch extractionError
        if isfolder(extractionDirectory)
            rmdir(extractionDirectory, "s");
        end

        if isfile(co2DatasetArchive)
            delete(co2DatasetArchive);
        end

        rethrow(extractionError);
    end

    exactExtractedDirectory = fullfile( ...
        extractionDirectory, co2DatasetName);

    lowercaseExtractedDirectory = fullfile( ...
        extractionDirectory, "co2lab_sampled_tables");

    if isfolder(exactExtractedDirectory)
        movefile(exactExtractedDirectory, co2DatasetDirectory);

    elseif isfolder(lowercaseExtractedDirectory)
        movefile(lowercaseExtractedDirectory, co2DatasetDirectory);

    else
        extractedContents = dir(extractionDirectory);
        extractedNames = {extractedContents.name};

        extractedContents = extractedContents( ...
            ~ismember(extractedNames, {".", "..", "__MACOSX"}));

        extractedDirectories = extractedContents( ...
            [extractedContents.isdir]);

        if numel(extractedDirectories) == 1
            extractedDirectory = fullfile( ...
                extractionDirectory, ...
                extractedDirectories(1).name);

            movefile(extractedDirectory, co2DatasetDirectory);
        else
            mkdir(co2DatasetDirectory);

            for extractedIndex = 1 : numel(extractedContents)
                sourcePath = fullfile( ...
                    extractionDirectory, ...
                    extractedContents(extractedIndex).name);

                destinationPath = fullfile( ...
                    co2DatasetDirectory, ...
                    extractedContents(extractedIndex).name);

                movefile(sourcePath, destinationPath);
            end
        end
    end

    if isfolder(extractionDirectory)
        rmdir(extractionDirectory, "s");
    end

    if isfile(co2DatasetArchive)
        delete(co2DatasetArchive);
    end

    fprintf( ...
        "Dataset installed in:\n  %s\n", ...
        co2DatasetDirectory);
else
    fprintf( ...
        "Required dataset already available:\n  %s\n", ...
        co2DatasetDirectory);
end

%% Initialize MRST and test utilities

run("../../startup.m")

