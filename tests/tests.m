%% Run regression tests

for iexample = 1 : numel(examples)

    ex = examples{iexample};

    fprintf("Running %s...\n", ex.name);

    outdir = fullfile(orig, "test_outputs", ex.name);

    cd(orig);

    if isfolder(outdir)
        remove_output_paths(outdir);
        rmdir(outdir, "s");
    end

    mkdir(outdir);

    exampledir = fullfile(orig, ex.ex_dir);
    exampleFile = fullfile(exampledir, [ex.name ".m"]);
    copiedExampleFile = fullfile(outdir, [ex.name ".m"]);

    assert(isfile(exampleFile), ...
        sprintf("Example file not found: %s", exampleFile));

    copyfile(exampleFile, copiedExampleFile);

    run_example(copiedExampleFile, outdir);

    for icase = 1 : numel(ex.outputs)

        currentCase = ex.outputs{icase};

        fprintf("  Checking %s...\n", currentCase.name);

        generated = fullfile( ...
            outdir, ex.vtk_dir, currentCase.generated);

        reference = fullfile( ...
            testsdir, "reference", currentCase.reference);

        assert(isfile(generated), ...
            sprintf("%s/%s: generated VTU not found: %s", ...
            ex.name, currentCase.name, generated));

        assert(isfile(reference), ...
            sprintf("%s/%s: reference VTU not found: %s", ...
            ex.name, currentCase.name, reference));

        currentData = read_vtu(generated);
        referenceData = read_vtu(reference);

        % Integer and topology fields
        for fieldIndex = 1 : numel(int_fields)

            fieldName = int_fields{fieldIndex};

            assert(isfield(currentData, fieldName), ...
                sprintf( ...
                "%s/%s: missing field '%s' in generated VTU", ...
                ex.name, currentCase.name, fieldName));

            assert(isfield(referenceData, fieldName), ...
                sprintf( ...
                "%s/%s: missing field '%s' in reference VTU", ...
                ex.name, currentCase.name, fieldName));

            assert(isequal( ...
                currentData.(fieldName), ...
                referenceData.(fieldName)), ...
                sprintf( ...
                "%s/%s: field '%s' differs from reference", ...
                ex.name, currentCase.name, fieldName));
        end

        % Floating-point fields
        for fieldIndex = 1 : numel(currentCase.float_fields)

            fieldName = currentCase.float_fields{fieldIndex};

            assert(isfield(currentData, fieldName), ...
                sprintf( ...
                "%s/%s: missing field '%s' in generated VTU", ...
                ex.name, currentCase.name, fieldName));

            assert(isfield(referenceData, fieldName), ...
                sprintf( ...
                "%s/%s: missing field '%s' in reference VTU", ...
                ex.name, currentCase.name, fieldName));

            currentValues = currentData.(fieldName);
            referenceValues = referenceData.(fieldName);

            assert(numel(currentValues) == numel(referenceValues), ...
                sprintf( ...
                "%s/%s: field '%s' size mismatch (%d vs %d)", ...
                ex.name, currentCase.name, fieldName, ...
                numel(currentValues), numel(referenceValues)));

            difference = abs(currentValues - referenceValues);

            allowedError = ...
                absolute_tol + relative_tol .* abs(referenceValues);

            failedValues = difference > allowedError;

            if any(failedValues)
                maximumDifference = max(difference);
                maximumAllowedError = max(allowedError);
                numberOfFailures = nnz(failedValues);

                error(sprintf([ ...
                    "%s/%s: field '%s' exceeds tolerance; " ...
                    "%d of %d values failed, " ...
                    "maximum absolute error = %e, " ...
                    "maximum allowed error = %e"], ...
                    ex.name, currentCase.name, fieldName, ...
                    numberOfFailures, numel(difference), ...
                    maximumDifference, maximumAllowedError));
            end
        end

        fprintf("    OK\n");
    end
end

cd(orig);

fprintf("\nAll regression tests passed.\n");
